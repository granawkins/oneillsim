export function neighborhoodFootprint(p, center) {
  const b = neighborhoodBounds[p.type], k = p.scale / 4;
  if (!b) throw new Error(`Unmeasured asset ${p.type}`);
  const c = Math.cos(p.rotation || 0), s = Math.sin(p.rotation || 0);
  const xx = [], zz = [];
  for (const x of b[0]) for (const z of b[2]) {
    xx.push((p.theta-center)*R + k*(c*x+s*z));
    zz.push(p.z + k*(-s*x+c*z));
  }
  return {xMin:Math.min(...xx), xMax:Math.max(...xx), zMin:Math.min(...zz), zMax:Math.max(...zz)};
}
export function neighborhoodFitsTube(p) {
  const b = neighborhoodBounds[p.type], k = p.scale/4;
  const c = Math.cos(p.rotation || 0), s = Math.sin(p.rotation || 0);
  for (const x of b[0]) for (const y of b[1]) for (const z of b[2]) {
    const tangent = k*(c*x+s*z), axial = p.z+k*(-s*x+c*z);
    const radial = Math.hypot(R-(p.surface.height+k*y), tangent);
    if (Math.hypot(radial-R, axial) >= TUBE-.1) return false;
  }
  return true;
}
function overlaps(a,b,gap=0) {
  return a.xMin < b.xMax+gap && a.xMax+gap > b.xMin && a.zMin < b.zMax+gap && a.zMax+gap > b.zMin;
}
function segmentRect(a,b,rect,padding) {
  // Liang-Barsky clip: complete segments, not merely sampled route points.
  let lo=0, hi=1;
  const dx=b[0]-a[0], dz=b[1]-a[1];
  for (const [p,q] of [[-dx,a[0]-rect.xMin+padding],[dx,rect.xMax+padding-a[0]],[-dz,a[1]-rect.zMin+padding],[dz,rect.zMax+padding-a[1]]]) {
    if (Math.abs(p)<1e-12) {if(q<0)return false;}
    else {const t=q/p; if(p<0)lo=Math.max(lo,t);else hi=Math.min(hi,t);if(lo>hi)return false;}
  }
  return true;
}
export function neighborhoodRouteIntersects(route, p, center, margin=0) {
  const box=neighborhoodFootprint(p,center);
  for(let i=1;i<route.points.length;i++) {
    const a=route.points[i-1],b=route.points[i];
    if(segmentRect([(a[0]-center)*R,a[1]],[(b[0]-center)*R,b[1]],box,route.width/2+margin))return true;
  }
  return false;
}
function decode(world) {
  if(!Array.isArray(world.assets)||!Array.isArray(world.assetTypes)||!world.masterPlan?.districts)throw new Error('Neighborhoods require the immutable source-world schema');
  return world.assets.filter(a=>!a[0].startsWith('settlement-')).map(a=>({id:a[0],type:world.assetTypes[a[1]],theta:a[2],z:a[3],scale:a[4],rotation:a[5]||0,parcel:a[6],surface:a[7]||{height:0}}));
}
